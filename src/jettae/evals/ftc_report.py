"""FTC evaluation, report: the markdown block of ``docs/eval_results.md``."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from jettae.sources.ftc.paths import long_path

POST_HOC_LABEL = "제시한 계산 중 정답을 포함한 비율"
_CHECK_LABEL = {"due_ok": "due date", "delay_ok": "delay days", "interest_ok": "interest"}

MD_START = "<!-- ftc_eval:start -->"
MD_END = "<!-- ftc_eval:end -->"


def update_markdown(path: Path, block: str) -> None:
    """Replace the ftc block in ``path`` (or append it); other evaluations' blocks are kept."""
    lp = long_path(path)
    text = lp.read_text(encoding="utf-8") if lp.exists() else "# Evaluation results\n"
    new = f"{MD_START}\n{block.rstrip()}\n{MD_END}\n"
    if MD_START in text and MD_END in text:
        pre, rest = text.split(MD_START, 1)
        _, post = rest.split(MD_END, 1)
        text = pre + new + post.lstrip("\n")
    else:
        text = text.rstrip("\n") + "\n\n" + new
    lp.write_text(text, encoding="utf-8")


def _pct(x: dict[str, Any]) -> str:
    if not x or not x.get("of"):
        return "n/a (0 rows)"
    return f"{x['n']}/{x['of']} ({x['rate'] * 100:.1f}%)"


SOURCE_LABEL = {
    "registry": "engine (registry rate)",
    "stated_rate": "engine delay days + rate stated in the decision",
    "mixed": "engine registry rate + rate stated in the decision",
    "no_rate": "engine (no interest rate involved)",
}


def _e1_computable(e1: dict[str, Any]) -> str:
    by = e1.get("engine_computable_by_source")
    if not by:
        return str(e1["engine_computable"])
    parts = []
    if by.get("registry"):
        parts.append(f"{by['registry']} with the engine's registry rate")
    if by.get("stated_rate"):
        parts.append(
            f"{by['stated_rate']} with delay days from the engine and the interest rate "
            "stated in the decision itself (partly circular: the rate comes from the text "
            "whose total is checked)"
        )
    if by.get("mixed"):
        parts.append(f"{by['mixed']} mixing both")
    if by.get("no_rate"):
        parts.append(f"{by['no_rate']} without an interest rate (delay-day ranges)")
    return f"{e1['engine_computable']} ({'; '.join(parts)})" if parts else "0"


def render_markdown(rep: dict[str, Any], results_path: str | None = None) -> str:
    """Markdown block for ``docs/eval_results.md``. ``results_path`` is the JSON file this
    report was written to (shown in the header, so a reviewer's re-run with ``--out`` cites
    its own file, not the tracked one)."""
    results = results_path or "data/results/ftc_eval.json"
    e2 = rep["E2"]["all_rows"]
    e2c = rep["E2"]["certain_rows_only"]
    rng = rep["E2"]["range_rows"]
    cond = rep["E2"]["no_base_date_rows_conditional_on_table_due"]
    e3 = rep["E3"]
    e1 = rep["E1"]["summary"]
    inp = rep["inputs"]
    lines = [
        "## FTC 의결서 — E1 / E2 / E3",
        "",
        f"Generated by `jettae eval ftc` at {rep['generated_at']} "
        f"(results: `{results}`). All numbers below come from that run.",
        "",
        f"- Inputs: {inp['rows']['n']} transcribed rows from {inp['images']} table images of "
        f"{len(inp['decisions'])} decisions ({', '.join(inp['decisions'])}); "
        f"rows sha256 `{(inp['rows']['sha256'] or '')[:12]}`, tables sha256 "
        f"`{(inp['tables']['sha256'] or '')[:12]}`, facts sha256 "
        f"`{(inp['facts']['sha256'] or '')[:12]}`. Transcription: {inp['transcription']}.",
        f"- Engine code sha256 `{rep['engine']['code_sha256'][:12]}`; tolerance: "
        f"{rep['engine']['tolerance']}.",
        "",
        "### E2 — rows with a base date (rollover x rounding variants)",
        "",
        f"Rows: {e2['rows']} (certain transcription only: {e2c['rows']}). "
        f"Engine abstained: {_pct(e2['abstained'])}. Engine computed due date, delay days "
        f"and interest in every variant: {_pct(e2['engine_full_computation'])}.",
        "",
        "Checks that can be scored per row (engine value and table value both present): "
        + ", ".join(f"{k} checks: {v} rows" for k, v in e2["evaluable_checks_per_row"].items())
        + "; rows with an evaluable check — "
        + ", ".join(f"{_CHECK_LABEL[k]} {v}" for k, v in e2["evaluable_rows_per_check"].items())
        + ".",
        "",
        "Single checks are rated over the rows where that check is evaluable. "
        "**All three** = due date, delay days and interest were all evaluated and all match, "
        "over all rows (a row whose table lacks a value is not a match). "
        "**All available** = every evaluable check matches (weaker).",
        "",
        "| variant | due date exact | delay days exact | interest within tol. "
        "| all three (all rows) | all three (fully evaluable rows) | all available "
        "| fully evaluable | engine computed all three |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for lab, per in e2["per_variant"].items():
        lines.append(
            f"| {lab} | {_pct(per['due_ok'])} | {_pct(per['delay_ok'])} | "
            f"{_pct(per['interest_ok'])} | {_pct(per['all_three_ok'])} | "
            f"{_pct(per['all_three_ok_of_fully_evaluable'])} | {_pct(per['all_available_ok'])} | "
            f"{_pct(per['fully_evaluable'])} | {_pct(per['engine_full_computation'])} |"
        )
    p = e2["post_hoc_any_variant"]
    pc = e2c["post_hoc_any_variant"]
    lines += [
        "",
        f"**{POST_HOC_LABEL}** (post hoc: a row counts when any of the 4 variants matches; "
        "the variant is chosen after seeing the table, so this is an upper bound, not the "
        "accuracy of one configuration): "
        f"due date {_pct(p['due_ok'])}, delay days {_pct(p['delay_ok'])}, interest "
        f"{_pct(p['interest_ok'])}, all three (all rows) {_pct(p['all_three_ok'])}, all "
        f"available {_pct(p['all_available_ok'])}. Certain-transcription rows: all three "
        f"{_pct(pc['all_three_ok'])}, all available {_pct(pc['all_available_ok'])}.",
        "",
        f"Rows where the engine registry has no interest-notice version for the delay period: "
        f"{e2['interest_not_computed_by_engine']}.",
    ]
    if "interest_with_stated_rate_when_engine_missing" in e2:
        lines.append(
            "For those rows, interest with the rate stated in the decision text: "
            + "; ".join(
                f"{k} {_pct(v)}"
                for k, v in e2["interest_with_stated_rate_when_engine_missing"].items()
            )
            + "."
        )
    lines += ["", "Variant sets whose available checks all match, per table (rows):", ""]
    for t, sets in e2["all_available_matched_variant_sets_by_table"].items():
        lines.append(f"- {t}: " + "; ".join(f"`{k}` x{v}" for k, v in sets.items()))
    lines += [
        "",
        f"Range rows (aggregated 기간 a ~ b; due dates of both endpoints): {rng['rows']} rows, "
        f"of which {rng['not_computed_no_rule_version']} not computed (no registered rule "
        f"version for those base dates); of the {rng['computed']} computed: "
        f"rollover_off {_pct(rng['rollover_off'])}, rollover_on {_pct(rng['rollover_on'])}, "
        f"{POST_HOC_LABEL} (post hoc) {_pct(rng['post_hoc_any_variant'])}.",
        "",
        "### E2-cond — rows without a base date, recomputed from the table's own due date",
        "",
        f"Rows: {cond['rows']}. "
        + "; ".join(
            f"{k}: delay {_pct(v['delay_ok'])}, interest {_pct(v['interest_ok'])}"
            for k, v in cond.items()
            if k != "rows"
        ),
        "",
        "### E3 — abstention when the base date is missing",
        "",
        f"- Rows without a base date: {e3['rows_without_base_date']}; engine abstained "
        f"(Insufficient): {_pct(e3['abstained_correctly'])}; with required documents: "
        f"{_pct(e3['with_required_documents'])}.",
        f"- Rows with a base date: {e3['rows_with_base_date']}; abstained because no rule "
        f"version is registered for the base date: {_pct(e3['abstained_no_rule_version'])}; "
        f"other abstentions: {_pct(e3['false_abstentions'])}.",
        "- Required documents listed: "
        + (", ".join(f"{k} (x{v})" for k, v in e3["required_documents_listed"].items()) or "-"),
        "",
        "### E1 — case-level figures",
        "",
        f"- Text facts linked to transcribed tables: {e1['facts_linked_to_transcribed_tables']}.",
        f"- Text total vs printed table total: {e1['text_vs_printed_total']['equal']}/"
        f"{e1['text_vs_printed_total']['compared']} equal; differences (KRW): "
        f"{e1['text_vs_printed_total']['differences_krw']}.",
        f"- Computable from the table rows (table has all rows): {_e1_computable(e1)}; not "
        f"computable because rows are elided (⋮): {e1['not_computable_rows_elided']}.",
        f"- Supplier/transaction counts in text vs transcribed 연번: "
        f"{e1['count_checks']['equal']}/{e1['count_checks']['compared']} equal.",
        "",
        "Column *computed / 연번*: per-variant sums of the row values, with their source in "
        "brackets. A sum marked *rate stated in the decision* is not an independent engine "
        "result: the delay days come from the engine, but the interest rate comes from the "
        "same decision text whose total it is compared with.",
        "",
        "| decision | table(s) | text claim | text value | printed total "
        "| computed / 연번 (source) |",
        "|---|---|---|---|---|---|",
    ]
    for c in rep["E1"]["checks"]:
        eng = c.get("reason", "") if c.get("engine_computable") is False else ""
        if "engine_sum_by_variant_krw" in c:
            eng = ", ".join(f"{k}={v}" for k, v in c["engine_sum_by_variant_krw"].items())
            src = c.get("interest_source")
            if src:
                eng += (
                    f" [{SOURCE_LABEL.get(src, src)}; rows: registry rate "
                    f"{c.get('rows_registry_rate', 0)}, stated rate {c.get('rows_stated_rate', 0)}]"
                )
        if "engine_min_by_variant" in c:
            eng = (
                ", ".join(
                    f"{k}={c['engine_min_by_variant'][k]}~{c['engine_max_by_variant'][k]}"
                    for k in c["engine_min_by_variant"]
                )
                + f" [{SOURCE_LABEL['no_rate']}]"
            )
        if "transcribed_distinct_serials" in c:
            eng = f"distinct 연번 {c['transcribed_distinct_serials']}"
        if "last_serial_no" in c:
            eng = f"last 연번 {c['last_serial_no']} (rows elided)"
        printed = c.get("printed_table_total_krw")
        diff = c.get("text_minus_printed_krw")
        lines.append(
            f"| {c['decision_id']} | {'+'.join(c['tables'])} | {c['fact_kind']} "
            f"(x{c.get('mentions', 1)}) | {c['text_value']} | "
            f"{'' if printed is None else f'{printed} (diff {diff})'}"
            f"{' — difference stated in text' if c.get('difference_stated_in_text') else ''}"
            f" | {eng} |"
        )
    qa = rep["E1"]["transcription_qa"]
    if qa:
        lines += ["", "Transcription QA (column sums of transcribed rows vs printed 합계):", ""]
        for q in qa:
            parts = [f"{col} diff={v['diff']}" for col, v in q.items() if isinstance(v, dict)]
            lines.append(f"- {q['decision_id']} {q['table_label']}: " + ", ".join(parts))
    lines += [
        "",
        "Notes: transcriptions are unverified (verified=no); table figures may be the "
        "respondent's submitted data as quoted in the decision. These results describe "
        "agreement between the engine and the published tables only.",
    ]
    return "\n".join(lines) + "\n"
